use super::*;
use quote::{ToTokens, quote};
use syn::Field;
use syn::punctuated::Punctuated;
use syn::token::Comma;

pub fn generate(fields: Punctuated<Field, Comma>, index_fields: &[Ident], timestamp: Option<&Ident>) -> Vec<proc_macro2::TokenStream> {
    let mut clauses: Vec<_> = index_fields
        .iter()
        .filter_map(|ident| fields.iter().find(|f| f.ident.as_ref() == Some(ident)).map(|field_def| index_filter(ident, &field_def.ty)))
        .collect();
    if let Some(ts_ident) = timestamp {
        clauses.push(quote! {
            if let Some(f) = filter.#ts_ident.as_ref() {
                match f {
                    pco_store::pco_pack::TimeFilter::Equal(v) => {
                        where_clauses.push(format!("end_at >= ${}", params.len() + 1));
                        params.push(v);
                        where_clauses.push(format!("start_at <= ${}", params.len() + 1));
                        params.push(v);
                    }
                    pco_store::pco_pack::TimeFilter::Inclusion(vals) => {
                        if !vals.is_empty() {
                            where_clauses.push(format!("end_at >= ${}", params.len() + 1));
                            params.push(vals.first().unwrap());
                            where_clauses.push(format!("start_at <= ${}", params.len() + 1));
                            params.push(vals.last().unwrap());
                        }
                    }
                    pco_store::pco_pack::TimeFilter::Range { start, end } => {
                        where_clauses.push(format!("end_at >= ${}", params.len() + 1));
                        params.push(start);
                        where_clauses.push(format!("start_at <= ${}", params.len() + 1));
                        params.push(end);
                    }
                }
            }
        });
    }
    clauses
}

fn index_filter(field: &Ident, rust_ty: &syn::Type) -> proc_macro2::TokenStream {
    let name = format!("{}", field);
    // pco_pack maps i32 to I64Filter; the supported types must match the Postgres column types
    // generated by `store::map_rust_type_to_pg`.
    let match_arms = match type_last_segment(rust_ty).as_deref() {
        Some("i64") => build_i64_filter(&name),
        Some("i32") => build_i32_filter(&name),
        Some("String") | Some("SmolStr") => build_string_filter(&name),
        Some("Uuid") => build_uuid_filter(&name),
        Some("bool") => build_bool_filter(&name),
        _ => panic!("unsupported index data type: {}; supported types are i64, i32, String, SmolStr, Uuid, and bool", rust_ty.to_token_stream()),
    };
    quote! {
        if let Some(f) = filter.#field.as_ref() {
            match f {
                #match_arms
            }
        }
    }
}

// Body of an Inclusion arm: one value renders as a plain equality, two or more values as a
// single `= ANY($n)` array parameter.
//
// Single values use equality deliberately. Postgres prunes LIST partitions for `col = $n` even in
// a generic plan (the OpExpr branch of match_clause_to_partition_key in partprune.c matches a
// scalar param), while for `col = ANY($n)` the array operand is a Param, which partprune gives up
// on, scanning every partition. Multi-value lists keep one ANY parameter so the number of distinct
// SQL texts, cached prepared statements, and server-side generic plans stays bounded; that loses
// pruning only for filters covering two but not all partitions, whereas the usual multi-granularity
// query wants all granularities and has nothing to prune. Single-element inclusion and Equal
// therefore generate identical SQL.
fn inclusion_arm(name: &str, cast: &str, any_cast: &str) -> proc_macro2::TokenStream {
    let eq_fmt = format!("{{}} = ${{}}{cast}");
    let any_fmt = format!("{{}} = ANY(${{}}{any_cast})");
    quote! {
        match vals.as_slice() {
            [] => {}
            [v] => {
                where_clauses.push(format!(#eq_fmt, #name, params.len() + 1));
                params.push(v);
            }
            _ => {
                where_clauses.push(format!(#any_fmt, #name, params.len() + 1));
                params.push(vals);
            }
        }
    }
}

fn build_i64_filter(name: &str) -> proc_macro2::TokenStream {
    let inclusion = inclusion_arm(name, "", "");
    quote! {
        pco_store::pco_pack::I64Filter::Equal(v) => {
            where_clauses.push(format!("{} = ${}", #name, params.len() + 1));
            params.push(v);
        }
        pco_store::pco_pack::I64Filter::Inclusion(vals) => {
            #inclusion
        }
        pco_store::pco_pack::I64Filter::Range { start, end } => {
            where_clauses.push(format!("{} >= ${} AND {} <= ${}", #name, params.len() + 1, #name, params.len() + 2));
            params.push(start);
            params.push(end);
        }
    }
}

// pco_pack represents i32 filters as I64Filter; the `::bigint` casts keep the comparison in
// the bigint domain, matching the i64 values bound by the client. Postgres still prunes and
// indexes int4 columns with such comparisons via the cross-type int4/int8 operators.
fn build_i32_filter(name: &str) -> proc_macro2::TokenStream {
    let inclusion = inclusion_arm(name, "::bigint", "::bigint[]");
    quote! {
        pco_store::pco_pack::I64Filter::Equal(val) => {
            where_clauses.push(format!("{} = ${}::bigint", #name, params.len() + 1));
            params.push(val);
        }
        pco_store::pco_pack::I64Filter::Inclusion(vals) => {
            #inclusion
        }
        pco_store::pco_pack::I64Filter::Range { start, end } => {
            where_clauses.push(format!("{} >= ${}::bigint AND {} <= ${}::bigint", #name, params.len() + 1, #name, params.len() + 2));
            params.push(start);
            params.push(end);
        }
    }
}

