//! The filesystem backends. `DurDir` is the durability
//! primitive every filesystem adapter builds on: whole files swap atomically,
//! write tmp, fsync the file, rename, fsync the parent directory.

use std::ffi::OsString;
use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

use anyhow::{Context, Result, bail};

static TMP_COUNTER: AtomicU64 = AtomicU64::new(0);

/// Whole-file durable storage over one directory: put writes tmp,
/// fsyncs, renames into place, and fsyncs the parent dir, so a reader sees
/// the whole new file or the whole previous one, never half of either. The
/// filesystem adapters generated by `#[derive(PcoStore)]` build on this.
pub struct DurDir {
    dir: PathBuf,
}

impl DurDir {
    /// Open (creating if needed) the durable directory.
    pub fn open(dir: impl AsRef<Path>) -> Result<Self> {
        let dir = dir.as_ref();
        fs::create_dir_all(dir).with_context(|| format!("create durable dir {}", dir.display()))?;
        Ok(Self { dir: dir.to_path_buf() })
    }

    /// Persist one file whole: tmp + fsync + atomic rename + parent dir fsync.
    /// A rename replaces an existing file atomically, so two writers of the
    /// same name never show a reader a mix.
    pub fn put(&self, name: &str, bytes: &[u8]) -> Result<()> {
        Self::check_name(name)?;
        let tmp = self.dir.join(format!(".tmp.{}.{}", std::process::id(), TMP_COUNTER.fetch_add(1, Ordering::Relaxed)));
        let mut file = OpenOptions::new().create_new(true).write(true).open(&tmp).with_context(|| format!("open temp {}", tmp.display()))?;
        file.write_all(bytes)?;
        file.sync_all()?;
        drop(file);
        fs::rename(&tmp, self.path(name)).with_context(|| format!("rename {} to {}", tmp.display(), self.path(name).display()))?;
        Self::sync_dir(&self.dir)?;
        Ok(())
    }

    /// Read one file whole, `None` when absent.
    pub fn get(&self, name: &str) -> Result<Option<Vec<u8>>> {
        Self::check_name(name)?;
        match fs::read(self.path(name)) {
            Ok(bytes) => Ok(Some(bytes)),
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(err) => Err(err).with_context(|| format!("read {}", self.path(name).display())),
        }
    }

    /// Every file name in the directory, excluding temp files.
    pub fn list_names(&self) -> Result<Vec<OsString>> {
        let mut names = Vec::new();
        for entry in fs::read_dir(&self.dir)? {
            let entry = entry?;
            if entry.file_name().to_string_lossy().starts_with(".tmp.") {
                continue;
            }
            names.push(entry.file_name());
        }
        Ok(names)
    }

    /// Delete one file, `true` when it existed.
    pub fn remove(&self, name: &str) -> Result<bool> {
        Self::check_name(name)?;
        match fs::remove_file(self.path(name)) {
            Ok(()) => Ok(true),
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => Ok(false),
            Err(err) => Err(err).with_context(|| format!("remove {}", self.path(name).display())),
        }
    }

    /// True when the name is present, saying nothing about whether it reads.
    pub fn contains(&self, name: &str) -> bool {
        Self::check_name(name).is_ok() && self.path(name).exists()
    }

    /// Delete abandoned temp files older than an hour; the hour keeps an
    /// in-flight put whole.
    pub fn sweep_stale_temps(&self) -> Result<usize> {
        let mut swept = 0;
        let now = std::time::SystemTime::now();
        for entry in fs::read_dir(&self.dir)? {
            let entry = entry?;
            if !entry.file_name().to_string_lossy().starts_with(".tmp.") {
                continue;
            }
            let stale =
                entry.metadata().and_then(|m| m.modified()).map(|t| now.duration_since(t).unwrap_or_default().as_secs() > 3600).unwrap_or(false);
            if stale {
                fs::remove_file(entry.path())?;
                swept += 1;
            }
        }
        Ok(swept)
    }

    /// The store directory.
    pub fn dir(&self) -> &Path {
        &self.dir
    }

    /// The path one name occupies in this directory.
    pub fn path(&self, name: &str) -> PathBuf {
        self.dir.join(name)
    }

    /// Names become file names here, so path separators never enter a name.
    fn check_name(name: &str) -> Result<()> {
        if name.is_empty() || name.contains('/') || name.contains('\\') || name.contains("..") {
            bail!("file name {name:?} is not a safe file name");
        }
        Ok(())
    }

    fn sync_dir(dir: &Path) -> Result<()> {
        let handle = OpenOptions::new().read(true).open(dir)?;
        handle.sync_all()?;
        Ok(())
    }
}

/// The filesystem adapter for one model: a durable directory holding
/// whole chunk files named by table, index key, and timestamp bounds. The
/// `#[derive(PcoStore)]` writes the `Backend` impl for each model:
/// names, narrowing, and marshaling need the model's field names, which only
/// expansion can see.
pub struct Fs {
    dur: DurDir,
}

impl Fs {
    /// Open (creating if needed) the adapter over `dir`.
    pub fn open(dir: impl AsRef<Path>) -> Result<Self> {
        Ok(Self { dur: DurDir::open(dir)? })
    }

    /// The durability primitive this adapter writes through.
    pub fn dur(&self) -> &DurDir {
        &self.dur
    }

    /// Delete abandoned temp files older than an hour.
    pub fn sweep_stale_temps(&self) -> Result<usize> {
        self.dur.sweep_stale_temps()
    }
}

/// Keep only ASCII letters and digits, mapping every other character to `-`.
/// Chunk file names are built from index field values, and a name must never
/// carry path separators; `-` cannot appear inside a sanitized value, so it
/// stays safe as a separator.
pub fn sanitize(value: &str) -> String {
    value.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '-' }).collect()
}

/// A stable 16-hex-character digest (FNV-1a) of chunk bytes, used as the
/// uniqueness suffix of chunk file names. SipHash is not stable
/// across releases, so names must not depend on it; this hash is plain and
/// frozen. Equal bytes give equal names, so a duplicate store overwrites
/// itself rather than duplicating rows.
pub fn fnv1a_hex(bytes: &[u8]) -> String {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in bytes {
        hash ^= *byte as u64;
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{hash:016x}")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dur_dir_roundtrips_lists_and_removes() {
        let dir = tempfile::TempDir::new().unwrap();
        let dur = DurDir::open(dir.path()).unwrap();
        dur.put("chunk-a", b"first bytes").unwrap();
        dur.put("chunk-b", b"second bytes").unwrap();
        let mut names: Vec<String> = dur.list_names().unwrap().into_iter().map(|n| n.to_string_lossy().into_owned()).collect();
        names.sort();
        assert_eq!(names, ["chunk-a", "chunk-b"]);
        assert_eq!(dur.get("chunk-a").unwrap().unwrap(), b"first bytes");
        assert!(dur.remove("chunk-a").unwrap());
        assert!(!dur.remove("chunk-a").unwrap());
        assert_eq!(dur.get("chunk-a").unwrap(), None);
    }

    #[test]
    fn dur_dir_refuses_unsafe_names() {
        let dir = tempfile::TempDir::new().unwrap();
        let dur = DurDir::open(dir.path()).unwrap();
        assert!(dur.put("../escape", b"x").is_err());
        assert!(dur.put("a/b", b"x").is_err());
        assert!(dur.put("", b"x").is_err());
    }

    #[test]
    fn fresh_temps_survive_sweep() {
        let dir = tempfile::TempDir::new().unwrap();
        let dur = DurDir::open(dir.path()).unwrap();
        fs::write(dir.path().join(".tmp.1.1"), b"").unwrap();
        assert_eq!(dur.sweep_stale_temps().unwrap(), 0, "an hour keeps in-flight temps");
    }
}
